"""Work order management service for generating, updating, and auditing maintenance orders."""

from datetime import datetime, timezone
import hashlib
import logging
from typing import Any, Dict, List, Optional

from src.agent.triage_agent import TriageDecision
from src.database.db_manager import DatabaseManager

logger = logging.getLogger(__name__)

VALID_STATUSES = {"Open", "InProgress", "Closed"}


class WorkOrderService:
    """Provides high-level business operations for maintenance work orders."""

    def __init__(self, db_manager: DatabaseManager) -> None:
        """Initialize WorkOrderService.

        Args:
            db_manager: DatabaseManager instance for SQLite operations.
        """
        self.db = db_manager

    def generate_wo_id(self, engine_id: int, cycle: int, severity: str) -> str:
        """Generate unique, human-readable work order identifier with deterministic hash.

        Format: 'WO-{engine_id}-{cycle}-{severity[:3].upper()}-{hash}'

        Args:
            engine_id: Engine identifier.
            cycle: Operating cycle.
            severity: Triage severity level ('Critical', 'Warning', etc.).

        Returns:
            str: Unique work order code.
        """
        sev_code = severity[:3].upper() if severity else "GEN"
        seed_str = f"{engine_id}-{cycle}-{severity}"
        hash_suffix = hashlib.sha256(seed_str.encode("utf-8")).hexdigest()[:6].upper()
        return f"WO-{engine_id}-{cycle}-{sev_code}-{hash_suffix}"

    def create_work_order(self, decision: TriageDecision) -> Dict[str, Any]:
        """Create a maintenance work order from a triage decision.

        Does not create work orders for nominal operation ('Normal') or data quality issues.
        Uses INSERT OR IGNORE to prevent duplicate work orders for the same engine, cycle,
        and severity.

        Args:
            decision: TriageDecision emitted by TriageAgent.

        Returns:
            dict: {'created': bool, 'wo_id': str, 'message': str}
        """
        if decision.severity in ("Normal", "DataQuality"):
            logger.debug(
                "Skipping work order generation for engine %d (cycle %d) with severity '%s'",
                decision.engine_id,
                decision.cycle,
                decision.severity,
            )
            return {
                "created": False,
                "wo_id": "",
                "message": f"Work order creation skipped for severity '{decision.severity}'.",
            }

        wo_id = self.generate_wo_id(decision.engine_id, decision.cycle, decision.severity)
        created_at = datetime.now(timezone.utc).isoformat()

        insert_sql = """
        INSERT OR IGNORE INTO work_orders (
            wo_id, engine_id, cycle, predicted_rul, anomaly_score,
            severity, reason, recommended_action, model_version,
            status, created_at, updated_at, triggered_rule, explanation
        ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 'Open', ?, ?, ?, ?);
        """

        params = (
            wo_id,
            decision.engine_id,
            decision.cycle,
            decision.predicted_rul,
            decision.anomaly_score,
            decision.severity,
            decision.triggered_rule,
            decision.recommended_action,
            decision.model_version,
            created_at,
            created_at,
            decision.triggered_rule,
            decision.explanation,
        )

        rows_affected = self.db.execute_write(insert_sql, params)

        if rows_affected > 0:
            # Record creation in lifecycle audit trail
            history_sql = """
            INSERT INTO wo_history (wo_id, old_status, new_status, changed_at, notes)
            VALUES (?, NULL, 'Open', ?, 'Work order generated by autonomous TriageAgent');
            """
            self.db.execute_write(history_sql, (wo_id, created_at))
            logger.info("Created work order %s for Engine %d", wo_id, decision.engine_id)
            return {
                "created": True,
                "wo_id": wo_id,
                "message": "Work order created successfully.",
            }
        else:
            # Lookup existing work order id for duplicate
            find_sql = """
            SELECT wo_id FROM work_orders
            WHERE engine_id = ? AND cycle = ? AND severity = ?;
            """
            existing = self.db.execute_query(
                find_sql, (decision.engine_id, decision.cycle, decision.severity)
            )
            existing_wo_id = existing[0]["wo_id"] if existing else wo_id
            logger.info(
                "Duplicate work order suppressed for Engine %d cycle %d: %s",
                decision.engine_id,
                decision.cycle,
                existing_wo_id,
            )
            return {
                "created": False,
                "wo_id": existing_wo_id,
                "message": "Work order already exists (duplicate suppressed).",
            }

    def update_status(
        self, wo_id: str, new_status: str, notes: str = ""
    ) -> bool:
        """Update work order status and record an immutable audit history event.

        Args:
            wo_id: Target work order identifier.
            new_status: New status ('Open', 'InProgress', 'Closed').
            notes: Optional technician notes or resolution comments.

        Returns:
            bool: True if status updated successfully, False if work order not found.

        Raises:
            ValueError: If new_status is not a recognized status state.
        """
        if new_status not in VALID_STATUSES:
            raise ValueError(
                f"Invalid status '{new_status}'. Allowed statuses are: {sorted(list(VALID_STATUSES))}"
            )

        current = self.get_work_order_by_id(wo_id)
        if not current:
            logger.warning("Work order %s not found for status update.", wo_id)
            return False

        old_status = current["status"]
        if old_status == new_status:
            logger.info("Work order %s already at status '%s'.", wo_id, new_status)
            return True

        updated_at = datetime.now(timezone.utc).isoformat()

        update_sql = """
        UPDATE work_orders
        SET status = ?, updated_at = ?
        WHERE wo_id = ?;
        """
        self.db.execute_write(update_sql, (new_status, updated_at, wo_id))

        history_sql = """
        INSERT INTO wo_history (wo_id, old_status, new_status, changed_at, notes)
        VALUES (?, ?, ?, ?, ?);
        """
        self.db.execute_write(history_sql, (wo_id, old_status, new_status, updated_at, notes))

        logger.info("Updated work order %s: %s -> %s", wo_id, old_status, new_status)
        return True

    def get_work_orders(
        self,
        engine_id: Optional[int] = None,
        severity: Optional[str] = None,
        status: Optional[str] = None,
    ) -> List[Dict[str, Any]]:
        """Query work orders with optional filtering by engine, severity, or status.

        Args:
            engine_id: Optional engine filter.
            severity: Optional severity level filter.
            status: Optional workflow status filter.

        Returns:
            list[dict]: List of matching work orders.
        """
        query = "SELECT * FROM work_orders WHERE 1=1"
        params: List[Any] = []

        if engine_id is not None:
            query += " AND engine_id = ?"
            params.append(engine_id)

        if severity is not None:
            query += " AND severity = ?"
            params.append(severity)

        if status is not None:
            query += " AND status = ?"
            params.append(status)

        query += " ORDER BY id DESC;"
        return self.db.execute_query(query, tuple(params))

    def get_work_order_by_id(self, wo_id: str) -> Optional[Dict[str, Any]]:
        """Retrieve a specific work order by its identifier.

        Args:
            wo_id: Work order identifier.

        Returns:
            dict or None: Work order record if found, else None.
        """
        rows = self.db.execute_query("SELECT * FROM work_orders WHERE wo_id = ?;", (wo_id,))
        return rows[0] if rows else None

    def get_work_order_history(self, wo_id: str) -> List[Dict[str, Any]]:
        """Retrieve complete transition audit history for a work order.

        Args:
            wo_id: Work order identifier.

        Returns:
            list[dict]: Sequential history log records.
        """
        return self.db.execute_query(
            "SELECT * FROM wo_history WHERE wo_id = ? ORDER BY id ASC;", (wo_id,)
        )

    def get_fleet_summary(self) -> Dict[str, Any]:
        """Aggregate total count, status breakdown, and severity distribution for the fleet.

        Returns:
            dict: {
                'total': int,
                'open': int,
                'in_progress': int,
                'closed': int,
                'by_severity': dict
            }
        """
        all_wos = self.db.execute_query("SELECT status, severity FROM work_orders;")
        total = len(all_wos)

        open_cnt = sum(1 for w in all_wos if w["status"] == "Open")
        in_prog_cnt = sum(1 for w in all_wos if w["status"] == "InProgress")
        closed_cnt = sum(1 for w in all_wos if w["status"] == "Closed")

        by_severity: Dict[str, int] = {}
        for w in all_wos:
            sev = w["severity"]
            by_severity[sev] = by_severity.get(sev, 0) + 1

        return {
            "total": total,
            "open": open_cnt,
            "in_progress": in_prog_cnt,
            "closed": closed_cnt,
            "by_severity": by_severity,
        }

    def process_triage_decisions(
        self, decisions: List[TriageDecision]
    ) -> List[Dict[str, Any]]:
        """Batch process a collection of triage decisions into work orders.

        Args:
            decisions: List of TriageDecision records.

        Returns:
            list[dict]: Results of creation attempts for each decision.
        """
        results = [self.create_work_order(decision) for decision in decisions]
        created_count = sum(1 for r in results if r["created"])
        logger.info(
            "Processed %d triage decisions -> %d work orders created.",
            len(decisions),
            created_count,
        )
        return results
